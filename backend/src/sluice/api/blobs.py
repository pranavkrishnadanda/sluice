"""Blob storage for uploads and run artefacts: RustFS (S3) in the stack, a directory in tests.

Keys are generated by the server (``uploads/<run_id>/input.csv``, ``runs/<run_id>/preview.parquet``)
and are never the client's file name. They are still validated (:func:`check_key`): ``/``-separated
segments of ``[A-Za-z0-9._-]``, no ``.``/``..`` segment, no leading/trailing/double ``/``, at most
:data:`MAX_KEY_CHARS` characters. So a key can never escape :class:`LocalBlobStore`'s root or the
S3 bucket.

``put_stream`` is the only path for untrusted bodies. It counts bytes as they arrive and raises
:class:`TooLarge` on the first chunk that takes the total past ``max_bytes``: at most
``max_bytes`` plus one chunk is read, the overflowing chunk is never written, and the partial
object is removed. Memory is O(one chunk). Blocking file and network calls run in
``asyncio.to_thread`` so the event loop is never blocked.
"""

import asyncio
import contextlib
import os
import re
import secrets
import shutil
import tempfile
from collections.abc import AsyncIterator, Callable, Iterator
from contextlib import AbstractContextManager, contextmanager
from pathlib import Path, PurePosixPath
from typing import Final, Protocol, Self, runtime_checkable
from urllib.parse import urlsplit

from pyarrow import NativeFile
from pyarrow.fs import FileType, S3FileSystem

from sluice.settings import Settings

MAX_KEY_CHARS: Final = 512
COPY_CHUNK_BYTES: Final = 1024 * 1024
S3_REGION: Final = "us-east-1"
S3_TIMEOUT_S: Final = 30.0
_SEGMENT = re.compile(r"^[A-Za-z0-9._-]+$")


class BlobError(Exception):
    """Base for blob store errors."""


class InvalidKey(BlobError, ValueError):
    """The key is not a safe relative ``/``-separated path."""


class TooLarge(BlobError):
    """More than ``max_bytes`` arrived; nothing was stored."""

    def __init__(self, max_bytes: int) -> None:
        super().__init__(f"more than {max_bytes} bytes")
        self.max_bytes = max_bytes


def check_key(key: str) -> str:
    """Return ``key`` if it is a safe relative object key, else raise :class:`InvalidKey`."""
    if not key or len(key) > MAX_KEY_CHARS:
        raise InvalidKey("blob key must be 1..512 characters")
    for segment in key.split("/"):
        if segment in ("", ".", "..") or not _SEGMENT.fullmatch(segment):
            raise InvalidKey("blob key segments must match [A-Za-z0-9._-]+ and not be . or ..")
    return key


def _check_limit(max_bytes: int) -> None:
    if max_bytes < 1:
        raise ValueError("max_bytes must be at least 1")


@runtime_checkable
class BlobStore(Protocol):
    """Where uploads and artefacts live. Implementations must be safe to share across threads."""

    async def put_stream(self, key: str, chunks: AsyncIterator[bytes], *, max_bytes: int) -> int:
        """Store the stream under ``key`` and return its size; :class:`TooLarge` over the limit."""
        ...

    def open_local(self, key: str) -> AbstractContextManager[Path]:
        """A temporary local copy of ``key`` (same suffix), removed when the context exits."""
        ...

    def put_bytes(self, key: str, data: bytes) -> None:
        """Store ``data`` under ``key``, replacing any existing object."""
        ...

    def get_bytes(self, key: str) -> bytes:
        """The whole object (meant for small artefacts); ``FileNotFoundError`` if missing."""
        ...

    def delete(self, key: str) -> None:
        """Remove ``key``; a missing key is not an error."""
        ...


async def _write_bounded(
    chunks: AsyncIterator[bytes], write: Callable[[bytes], object], max_bytes: int
) -> int:
    """Write chunks through ``write`` (in a thread) until done; raise once past ``max_bytes``."""
    total = 0
    async for chunk in chunks:
        total += len(chunk)
        if total > max_bytes:
            raise TooLarge(max_bytes)
        if chunk:
            await asyncio.to_thread(write, chunk)
    return total


@contextmanager
def _temp_copy(key: str, copy_into: Callable[[Path], None]) -> Iterator[Path]:
    """A private temp dir holding ``blob<suffix>``; ``copy_into`` fills it. Removed on exit."""
    tmp_dir = Path(tempfile.mkdtemp(prefix="sluice-blob-"))
    try:
        local = tmp_dir / f"blob{PurePosixPath(key).suffix}"
        copy_into(local)
        yield local
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)



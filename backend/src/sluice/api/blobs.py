# Local directory
# --------------------------------------------------------------------------------------------


class LocalBlobStore:
    """Blobs as files under ``root`` (tests, and running without RustFS).

    Writes go to a hidden ``.part`` file in the target directory and are renamed into place, so a
    reader never sees a partial object.
    """

    __slots__ = ("root",)

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = self.root.joinpath(*check_key(key).split("/"))
        if not path.is_relative_to(self.root):  # defence in depth; check_key already ensures it
            raise InvalidKey("blob key escapes the store root")
        return path

    def _part(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        return path.with_name(f".{path.name}.{secrets.token_hex(8)}.part")

    async def put_stream(self, key: str, chunks: AsyncIterator[bytes], *, max_bytes: int) -> int:
        """See :meth:`BlobStore.put_stream`."""
        _check_limit(max_bytes)
        path = self._path(key)
        part = self._part(path)
        try:
            with part.open("wb") as fh:
                total = await _write_bounded(chunks, fh.write, max_bytes)
            os.replace(part, path)
        except BaseException:
            part.unlink(missing_ok=True)
            raise
        return total

    def open_local(self, key: str) -> AbstractContextManager[Path]:
        """See :meth:`BlobStore.open_local`."""
        source = self._path(key)
        return _temp_copy(key, lambda local: shutil.copyfile(source, local))

    def put_bytes(self, key: str, data: bytes) -> None:
        """See :meth:`BlobStore.put_bytes`."""
        path = self._path(key)
        part = self._part(path)
        try:
            part.write_bytes(data)
            os.replace(part, path)
        except BaseException:
            part.unlink(missing_ok=True)
            raise

    def get_bytes(self, key: str) -> bytes:
        """See :meth:`BlobStore.get_bytes`."""
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        """See :meth:`BlobStore.delete`."""
        self._path(key).unlink(missing_ok=True)



def _endpoint(url: str) -> tuple[str, str]:
    """``http://localhost:59000`` -> (``"http"``, ``"localhost:59000"``)."""
    parts = urlsplit(url)
    if parts.scheme not in ("http", "https") or not parts.netloc or parts.path not in ("", "/"):
        raise ValueError("S3 endpoint must be http(s)://host[:port]")
    return parts.scheme, parts.netloc


class S3BlobStore:
    """Blobs in one bucket on RustFS through ``pyarrow.fs.S3FileSystem`` (path-style).

    The bucket is created if missing. Bucket deletion is disabled on this filesystem. Every
    request has connect/request timeouts (:data:`S3_TIMEOUT_S`). The credentials are held only by
    the pyarrow filesystem; nothing here logs or returns them.
    """

    __slots__ = ("bucket", "fs")

    def __init__(
        self,
        *,
        endpoint: str,
        access_key: str,
        secret_key: str,
        bucket: str,
        region: str = S3_REGION,
        timeout_s: float = S3_TIMEOUT_S,
    ) -> None:
        scheme, netloc = _endpoint(endpoint)
        self.bucket = check_key(bucket)
        if "/" in bucket:
            raise InvalidKey("bucket name must not contain /")
        self.fs = S3FileSystem(
            access_key=access_key,
            secret_key=secret_key,
            endpoint_override=netloc,
            scheme=scheme,
            region=region,
            connect_timeout=timeout_s,
            request_timeout=timeout_s,
            force_virtual_addressing=False,
            allow_bucket_creation=True,
            allow_bucket_deletion=False,
        )
        self._ensure_bucket()

    @classmethod
    def from_settings(cls, settings: Settings, bucket: str) -> Self:
        """The store for ``bucket`` on the stack's RustFS (endpoint and keys from ``settings``)."""
        return cls(
            endpoint=settings.s3_endpoint,
            access_key=settings.rustfs_access_key.get_secret_value(),
            secret_key=settings.rustfs_secret_key.get_secret_value(),
            bucket=bucket,
        )

    def _ensure_bucket(self) -> None:
        if self.fs.get_file_info(self.bucket).type == FileType.Directory:
            return
        try:
            self.fs.create_dir(self.bucket)
        except OSError:
            # Another process may have created it between the check and the call.
            if self.fs.get_file_info(self.bucket).type != FileType.Directory:
                raise

    def _path(self, key: str) -> str:
        return f"{self.bucket}/{check_key(key)}"

    def _remove(self, path: str) -> None:
        with contextlib.suppress(FileNotFoundError):
            self.fs.delete_file(path)

    async def put_stream(self, key: str, chunks: AsyncIterator[bytes], *, max_bytes: int) -> int:
        """See :meth:`BlobStore.put_stream`.

        pyarrow has no multipart abort, so on failure the stream is closed (which may publish
        what was written) and the object is deleted.
        """
        _check_limit(max_bytes)
        path = self._path(key)
        stream: NativeFile = await asyncio.to_thread(self.fs.open_output_stream, path)
        try:
            total = await _write_bounded(chunks, stream.write, max_bytes)
            await asyncio.to_thread(stream.close)
        except BaseException:
            await asyncio.to_thread(self._discard, stream, path)
            raise
        return total

    def _discard(self, stream: NativeFile, path: str) -> None:
        with contextlib.suppress(OSError):
            stream.close()
        self._remove(path)

    def _download(self, key: str, local: Path) -> None:
        with self.fs.open_input_stream(self._path(key)) as src, local.open("wb") as dst:
            while chunk := src.read(COPY_CHUNK_BYTES):
                dst.write(chunk)

    def open_local(self, key: str) -> AbstractContextManager[Path]:
        """See :meth:`BlobStore.open_local`. Streams the object to disk in 1 MB chunks."""
        check_key(key)
        return _temp_copy(key, lambda local: self._download(key, local))

    def put_bytes(self, key: str, data: bytes) -> None:
        """See :meth:`BlobStore.put_bytes`."""
        with self.fs.open_output_stream(self._path(key)) as out:
            out.write(data)

    def get_bytes(self, key: str) -> bytes:
        """See :meth:`BlobStore.get_bytes`."""
        with self.fs.open_input_stream(self._path(key)) as src:
            return src.read()

    def delete(self, key: str) -> None:
        """See :meth:`BlobStore.delete`."""
        self._remove(self._path(key))
